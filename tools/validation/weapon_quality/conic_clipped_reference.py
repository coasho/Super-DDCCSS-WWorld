"""Independent conic/Gaussian references for six captured optical requests.

The integral uses NIST DLMF 7.1 Gaussian definitions and a direct quadratic
normalized-ray horizon, evaluated by mpmath rather than the native polynomial
moment implementation. This script does not import or execute the SDK.
"""
import argparse
import json
import pathlib
import struct
import mpmath as mp

decode = lambda value: struct.unpack('>d', bytes.fromhex(value))[0]

def calculate(c,dps):
 mp.mp.dps=dps;r=[mp.mpf(decode(s)) for s in c['region_bits']];cut=mp.mpf(decode(c['cutoff_bits']));v=list(map(mp.mpf,c['normalized_axes_binary64']));f,u,right,up=[v[k:k+3] for k in [0,3,6,9]]
 dot=lambda a,b:sum(x*y for x,y in zip(a,b));a,b,cc=dot(f,u),dot(right,u),dot(up,u);g00,g01,g02,g11,g12,g22=dot(f,f),dot(f,right),dot(f,up),dot(right,right),dot(right,up),dot(up,up)
 def horizon(x):
  X=mp.tan(x);n=a+b*X;A=cc*cc-cut*cut*g22;B=2*(n*cc-cut*cut*(g02+g12*X));C=n*n-cut*cut*(g00+2*g01*X+g11*X*X)
  return mp.atan((-B+mp.sign(cut)*mp.sqrt(B*B-4*A*C))/(2*A))
 cuts=[r[0],r[1]]
 for y in [r[2],r[3]]:
  Y=mp.tan(y);n=a+cc*Y;A=b*b-cut*cut*g11;B=2*(n*b-cut*cut*(g01+g12*Y));C=n*n-cut*cut*(g00+2*g02*Y+g22*Y*Y);D=B*B-4*A*C
  if D>0:
   for sign in [-1,1]:
    X=(-B+sign*mp.sqrt(D))/(2*A);x=mp.atan(X)
    if r[0]<x<r[1] and mp.sign(n+b*X)==mp.sign(cut):cuts.append(x)
 cuts=sorted(cuts);pitch=mp.mpf(.0015);sigma=mp.mpf(.00075)
 Phi=lambda z:mp.erfc(-z/mp.sqrt(2))/2
 J=lambda z:z*Phi(z)+mp.exp(-z*z/2)/mp.sqrt(2*mp.pi)
 def vertical(A,B,low,high):
  if B<=A:return mp.mpf(0)
  if low+high>A+B:A,B,low,high=-B,-A,-high,-low
  return sigma*(J((high-A)/sigma)-J((high-B)/sigma)-J((low-A)/sigma)+J((low-B)/sigma))
 result=[]
 for xat in [r[0]+sigma/2,(r[0]+r[1])/2,r[1]-sigma/2]:
  col=max(0,min(63,int(mp.floor(xat/pitch+32))));row=max(0,min(63,int(mp.floor(horizon(xat)/pitch+32))))
  xl=mp.mpf((col-32)*.0015);xh=mp.mpf(float(xl)+.0015);yl=mp.mpf((row-32)*.0015);yh=mp.mpf(float(yl)+.0015)
  def integrand(x):
   h=min(r[3],max(r[2],horizon(x)))
   return (Phi((xh-x)/sigma)-Phi((xl-x)/sigma))*vertical(r[2],h,yl,yh)/(pitch*pitch)
  value=mp.quad(integrand,cuts)
  result.append((row,col,value))
 return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    root = pathlib.Path(__file__).resolve().parents[3]
    parser.add_argument('--fixture', type=pathlib.Path,
                        default=root/'tests/simulation/fixtures/thermal_conic_v5_clipped.json')
    parser.add_argument('--output', required=True, type=pathlib.Path)
    parser.add_argument('--header', type=pathlib.Path)
    parser.add_argument('--precision', type=int, default=120)
    args = parser.parse_args()
    if args.precision < 80:
        parser.error('Independent reference requires at least 80 decimal digits')
    fixture = json.loads(args.fixture.read_text(encoding='utf-8'))
    cases = fixture['cases']
    results = []
    header = ['// Generated by conic_clipped_reference.py; independent numerical references.',
              '#pragma once', '#include <array>',
              'namespace thermal_conic_v5_clipped_reference {',
              'struct Sample {unsigned row,col;double expected;};',
              'struct Case {const char* id;std::array<double,3> pointing,up;double cutoff;',
              '    std::array<double,4> region;std::array<Sample,3> reference;};',
              'inline const std::array<Case,6> cases{{']
    for case in cases:
        samples = calculate(case, args.precision)
        results.append(dict(id=case['id'], samples=[dict(row=row,col=col,
            expected=mp.nstr(value,args.precision-10)) for row,col,value in samples]))
        vector = lambda bits: '{'+','.join(decode(x).hex() for x in bits)+'}'
        points = '{'+','.join('Sample{'+str(row)+','+str(col)+','+float(value).hex()+'}'
                              for row,col,value in samples)+'}'
        header.append('    Case{"'+case['id']+'",'+vector(case['pointing_bits'])+','+
            vector(case['up_bits'])+','+decode(case['cutoff_bits']).hex()+','+
            vector(case['region_bits'])+','+points+'},')
        print(case['id'], 'reference points', len(samples), flush=True)
    header.extend(['}};', '} // namespace thermal_conic_v5_clipped_reference', ''])
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(dict(reference=fixture['definition'],
        precision=args.precision, scope=fixture['scope'], cases=results),indent=2)+'\n',encoding='utf-8')
    if args.header:
        args.header.write_text('\n'.join(header),encoding='utf-8')

if __name__ == '__main__':
    main()
