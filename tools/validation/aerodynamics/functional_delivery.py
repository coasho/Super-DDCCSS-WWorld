"""Inventory current functional-repair products without claiming regeneration or closure.

The prior generation receipt is retained as historical evidence. Changed hover
profiles are generated by the normal fly stage. Full-table inspection, current
product binding and original functional outcomes are separate observations.
"""
import argparse
import hashlib
import json
from pathlib import Path
import time
import xml.etree.ElementTree as ET

from engineering_inventory import inspect
from engineering_delivery import cells, knots

ROOT = Path(__file__).resolve().parents[3]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, value):
    path.write_text(json.dumps(value, indent=2, allow_nan=False) + '\n', encoding='utf-8')


def main(args):
    start = time.monotonic()
    source = Path(args.matrix).resolve()
    out = Path(args.output).resolve()
    prefix = Path(args.prefix).resolve()
    for path in (source, out, prefix):
        if '.codex' in {p.casefold() for p in path.parts}:
            raise ValueError('Excluded path')
    if not out.is_relative_to(ROOT / 'build'):
        raise ValueError('Evidence must remain under the owned build directory')
    matrix = json.loads(source.read_text(encoding='utf-8'))
    products, changes, rows, drift = {}, [], [], {}
    for design in matrix['designs']:
        tables = []
        for relative, old_hash in design['products'].items():
            actual = ROOT / 'aircraft' / relative
            current = sha(actual)
            for target in (prefix / 'share/flightsim/aircraft' / relative,
                           ROOT / 'build/ucrt64-release/share/flightsim/aircraft' / relative,
                           ROOT / 'build/ucrt64-headless/share/flightsim/aircraft' / relative):
                if sha(target) != current:
                    raise ValueError('Consumer product mismatch: ' + str(target))
            products[relative] = current
            if current != old_hash:
                changes.append(dict(path=relative, original_sha256=old_hash, current_sha256=current))
            if actual.suffix == '.xml':
                tables.extend(inspect(actual))
        for relative, old_hash in design['generator_sha256'].items():
            current = sha(ROOT / relative)
            if current != old_hash:
                drift[relative] = dict(original_sha256=old_hash, current_sha256=current)
        for relative, old_hash in design['input_sha256'].items():
            if sha(ROOT / relative) != old_hash:
                raise ValueError('Authored geometry/card changed; requires generation: ' + relative)
        rows.append(dict(name=design['name'], category=design['category'], tables=tables,
                         table_count=len(tables), passed=bool(tables) and all(t['passed'] for t in tables)))
    cases = {}
    for filename in args.results:
        path = Path(filename).resolve()
        tree = ET.parse(path).getroot()
        for case in tree.findall('TestCase'):
            result = case.find('OverallResult')
            cases[case.attrib['name']] = dict(passed=result.get('success') == 'true',
                kind='method' if '[control]' in case.get('tags', '') else 'original-functional',
                source=str(path), source_sha256=sha(path),
                failed_assertions=[dict(expression=e.findtext('Original'), actual=e.findtext('Expanded'))
                                   for e in case.findall('.//Expression') if e.get('success') == 'false'])
    dll = ROOT / 'build/ucrt64-release/bin/libfsim.dll'
    if sha(prefix / 'bin/libfsim.dll') != sha(dll):
        raise ValueError('Installed native DLL mismatch')
    result = dict(schema='fsim.sim-m02.functional-repair-delivery.v1',
        formal_sim_m02_accepted=False,
        reason='Original functional gates have failures; no fresh complete regression/flight campaign is claimed.',
        prior_generation_matrix=str(source), prior_generation_matrix_sha256=sha(source),
        historical_engineering_counts=matrix['counts'],
        generation_reused=True, generation_reused_scope='Existing unchanged geometry/card aerodynamic products; no new all88 generation claimed',
        generation_source_drift=drift, changed_generated_products=changes,
        products=products, installed_prefix=str(prefix), loaded_release_dll_sha256=sha(dll),
        full_table_design_count=len(rows), full_table_count=sum(r['table_count'] for r in rows),
        native_xml_coefficient_cells=sum(cells(t) for r in rows for t in r['tables']),
        native_xml_axis_knots=sum(knots(t) for r in rows for t in r['tables']),
        full_table_failures=[r['name'] for r in rows if not r['passed']],
        selected_native_cases=cases,
        selected_native_counts={kind: dict(passed=sum(r['passed'] for r in cases.values() if r['kind'] == kind),
            failed=sum(not r['passed'] for r in cases.values() if r['kind'] == kind))
            for kind in ('method', 'original-functional')},
        full_regression_executed=False, elapsed_seconds=time.monotonic() - start)
    write(out / 'current-native-table-inventory.json', dict(designs=rows, table_count=result['full_table_count']))
    write(out / 'matrix.json', dict(schema='fsim.sim-m02.functional-evidence-matrix.v1',
        formal_sim_m02_accepted=False, historical_engineering_counts=matrix['counts'],
        status_scope='Retained engineering construction labels; not current whole-function acceptance',
        source_matrix=str(source), source_matrix_sha256=sha(source),
        designs=[dict(name=d['name'], category=d['category'], status=d['status'],
            components=d['components'], functional_acceptance_established=False,
            original_generation_sources=d['generator_sha256'], original_authored_inputs=d['input_sha256'],
            current_products={p: products[p] for p in d['products']},
            current_full_table_check=next(r['passed'] for r in rows if r['name'] == d['name']))
            for d in matrix['designs']]))
    write(out / 'functional-delivery.json', result)
    print(json.dumps({k: v for k, v in result.items() if k not in ('products', 'selected_native_cases')}, indent=2))
    return int(bool(result['full_table_failures']))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--matrix', required=True)
    parser.add_argument('--output', required=True)
    parser.add_argument('--prefix', required=True)
    parser.add_argument('--results', nargs='+', required=True)
    raise SystemExit(main(parser.parse_args()))
