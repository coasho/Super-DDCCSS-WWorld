import ctypes
from ctypes import wintypes
import errno
import json
import os
from pathlib import Path
import struct
import tempfile
import unittest
from unittest import mock

from hangar import files, model3d


@contextmanager
def mapped_reader(path, share_delete):
    kernel = ctypes.WinDLL('kernel32', use_last_error=True)
    kernel.CreateFileW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                                  ctypes.c_void_p, wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE]
    kernel.CreateFileW.restype = wintypes.HANDLE
    kernel.CreateFileMappingW.argtypes = [wintypes.HANDLE, ctypes.c_void_p, wintypes.DWORD,
                                         wintypes.DWORD, wintypes.DWORD, wintypes.LPCWSTR]
    kernel.CreateFileMappingW.restype = wintypes.HANDLE
    kernel.MapViewOfFile.argtypes = [wintypes.HANDLE, wintypes.DWORD, wintypes.DWORD,
                                    wintypes.DWORD, ctypes.c_size_t]
    kernel.MapViewOfFile.restype = ctypes.c_void_p
    kernel.UnmapViewOfFile.argtypes = [ctypes.c_void_p]
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    handle = kernel.CreateFileW(str(path), 0x80000000, 3 | (4 if share_delete else 0),
                                None, 3, 0, None)
    if handle == ctypes.c_void_p(-1).value:
        raise ctypes.WinError(ctypes.get_last_error())
    mapping = view = None
    try:
        mapping = kernel.CreateFileMappingW(handle, None, 2, 0, 0, None)
        if not mapping:
            raise ctypes.WinError(ctypes.get_last_error())
        view = kernel.MapViewOfFile(mapping, 4, 0, 0, 0)
        if not view:
            raise ctypes.WinError(ctypes.get_last_error())
        yield view
    finally:
        if view:
            kernel.UnmapViewOfFile(view)
        if mapping:
            kernel.CloseHandle(mapping)
        kernel.CloseHandle(handle)


class GlbPublication(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir='D:/ENV/tmp' if os.name == 'nt' else None)
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.path = self.root/'fixture.glb'
        self.manifest = self.root/'fixture.glb.manifest'
        self.old = b'original mapped reader bytes\n'*8
        self.path.write_bytes(self.old)
        self.manifest.write_bytes(b'old manifest\n')

    def builder(self):
        b = model3d._Builder()
        b.bin = bytearray(b'\x00\x01\xff\x05\x19')
        b.nodes = [dict(name='asymmetric', translation=[1.25, -2., 3.5])]
        b.liquid_boundary_v1 = dict(schema='fixture', positions=0, indices=1)
        return b

    def oracle(self, builder):
        binary = bytes(builder.bin)+b'\0'*((-len(builder.bin)) % 4)
        nodes = copy.deepcopy(builder.nodes)+[dict(name='fixture', children=[0])]
        doc = dict(asset=dict(version='2.0', generator='hangar'), scene=0,
                   scenes=[dict(nodes=[1])], nodes=nodes, meshes=[], materials=[], accessors=[],
                   bufferViews=[], buffers=[dict(byteLength=len(binary))],
                   extras=dict(fsim_liquid_boundary_v1=dict(builder.liquid_boundary_v1, node=1)))
        raw = json.dumps(doc, separators=(',', ':')).encode()
        raw += b' '*((-len(raw)) % 4)
        glb = (struct.pack('<III', 0x46546c67, 2, 28+len(raw)+len(binary))+
               struct.pack('<II', len(raw), 0x4e4f534a)+raw+
               struct.pack('<II', len(binary), 0x004e4942)+binary)
        manifest = ('# Generated by hangar: glTF x = -y, y = up, z = forward (nose); origin at the CG.\n'
                    'forward -y\nup +z\nscale 1.0\n'+'fixture \u03bc\n').encode('utf-8')
        return glb, manifest

    def clean(self):
        self.assertEqual(sorted(p.name for p in self.root.iterdir()), ['fixture.glb', 'fixture.glb.manifest'])

    def test_actual_finish_retains_exact_glb_and_manifest_bytes(self):
        b = self.builder(); expected = self.oracle(b)
        self.assertEqual(model3d.finish(b, [0], 'fixture', str(self.path), ['fixture \u03bc']), str(self.path))
        self.assertEqual(self.path.read_bytes(), expected[0])
        self.assertEqual(self.manifest.read_bytes(), expected[1]); self.clean()

    def test_atomic_stream_is_closed_and_complete_before_replace(self):
        original = files._publish_closed
        seen = []
        def replace(source, destination):
            self.assertTrue(stream.closed)
            self.assertEqual(Path(source).parent, Path(destination).parent)
            self.assertEqual(Path(source).read_bytes(), b'complete new bytes')
            self.assertEqual(Path(destination).read_bytes(), self.old)
            seen.append(True); return original(source, destination)
        with mock.patch.object(files, '_publish_closed', side_effect=replace):
            with files.atomic_write_stream(self.path, 'wb') as stream:
                stream.write(b'complete new bytes')
        self.assertEqual(seen, [True]); self.assertEqual(self.path.read_bytes(), b'complete new bytes'); self.clean()

    def fail_stream(self, phase):
        factory = files.tempfile.NamedTemporaryFile
        class FailingStream:
            def __init__(self, stream): self.stream = stream
            def __getattr__(self, name): return getattr(self.stream, name)
            def __enter__(self): return self
            def __exit__(self, *args): return self.stream.__exit__(*args)
            def write(self, value):
                if phase == 'write': raise OSError(errno.ENOSPC, 'declared write failure')
                return self.stream.write(value)
            def flush(self):
                if phase == 'flush': raise OSError(errno.EIO, 'declared flush failure')
                return self.stream.flush()
        with mock.patch.object(files.tempfile, 'NamedTemporaryFile', side_effect=lambda **kw: FailingStream(factory(**kw))):
            with self.assertRaises(OSError):
                model3d.finish(self.builder(), [0], 'fixture', str(self.path), ['fixture \u03bc'])
        self.assertEqual(self.path.read_bytes(), self.old)
        self.assertEqual(self.manifest.read_bytes(), b'old manifest\n'); self.clean()

    def test_finish_write_failure_preserves_original_destinations(self): self.fail_stream('write')
    def test_finish_flush_failure_preserves_original_destinations(self): self.fail_stream('flush')

    def test_finish_fsync_failure_preserves_original_destinations(self):
        with mock.patch.object(files.os, 'fsync', side_effect=OSError(errno.EIO, 'declared fsync failure')):
            with self.assertRaises(OSError): model3d.finish(self.builder(), [0], 'fixture', str(self.path))
        self.assertEqual(self.path.read_bytes(), self.old)
        self.assertEqual(self.manifest.read_bytes(), b'old manifest\n'); self.clean()

    def test_finish_replace_failure_preserves_original_destinations(self):
        with mock.patch.object(files, '_publish_closed', side_effect=OSError(errno.ENOSPC, 'declared rename failure')):
            with self.assertRaises(OSError): model3d.finish(self.builder(), [0], 'fixture', str(self.path))
        self.assertEqual(self.path.read_bytes(), self.old)
        self.assertEqual(self.manifest.read_bytes(), b'old manifest\n'); self.clean()

    def test_text_stream_uses_utf8_lf_and_preserves_destination_on_failure(self):
        with files.atomic_write_stream(self.manifest, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write('new \u03bc\n')
        self.assertEqual(self.manifest.read_bytes(), 'new \u03bc\n'.encode('utf-8'))
        with self.assertRaisesRegex(RuntimeError, 'abort'):
            with files.atomic_write_stream(self.manifest, 'w', encoding='utf-8', newline='\n') as stream:
                stream.write('partial'); raise RuntimeError('abort')
        self.assertEqual(self.manifest.read_bytes(), 'new \u03bc\n'.encode('utf-8')); self.clean()

    def test_manifest_publication_failure_keeps_its_old_bytes_without_claiming_pair_atomicity(self):
        b = self.builder(); expected = self.oracle(b)
        original = files._publish_closed
        def publish(source, destination):
            if Path(destination) == self.manifest:
                raise OSError(errno.ENOSPC, 'declared manifest publication failure')
            return original(source, destination)
        with mock.patch.object(files, '_publish_closed', side_effect=publish):
            with self.assertRaises(OSError): model3d.finish(b, [0], 'fixture', str(self.path), ['fixture \u03bc'])
        self.assertEqual(self.path.read_bytes(), expected[0])
        self.assertEqual(self.manifest.read_bytes(), b'old manifest\n'); self.clean()

    def test_unknown_stream_mode_refuses_before_touching_destination(self):
        with self.assertRaises(ValueError):
            with files.atomic_write_stream(self.path, 'ab'): pass
        self.assertEqual(self.path.read_bytes(), self.old); self.clean()

    @unittest.skipUnless(os.name == 'nt', 'Windows unsupported-operation refusal')
    def test_unsupported_native_fallback_refuses_old_file_without_retry_or_truncate(self):
        with mock.patch.object(files.os, 'replace', side_effect=ctypes.WinError(5)), \
             mock.patch.object(files, '_windows_rename_closed', side_effect=ctypes.WinError(50)), \
             mock.patch.object(files.time, 'sleep') as sleep:
            with self.assertRaises(OSError) as refused:
                model3d.finish(self.builder(), [0], 'fixture', str(self.path))
        self.assertEqual(refused.exception.winerror, 50)
        self.assertEqual(sleep.call_count, 0)
        self.assertEqual(self.path.read_bytes(), self.old)
        self.assertEqual(self.manifest.read_bytes(), b'old manifest\n'); self.clean()

    @unittest.skipUnless(os.name == 'nt', 'Windows mapped-file semantics')
    def test_real_delete_sharing_mapping_refuses_direct_truncate_but_finish_replaces(self):
        b = self.builder(); expected = self.oracle(b)
        with mapped_reader(self.path, True) as view:
            with self.assertRaises(OSError):
                with open(self.path, 'wb'): pass
            self.assertEqual(self.path.read_bytes(), self.old)
            model3d.finish(b, [0], 'fixture', str(self.path), ['fixture \u03bc'])
            self.assertEqual(self.path.read_bytes(), expected[0])
            self.assertEqual(ctypes.string_at(view, len(self.old)), self.old)
        self.assertEqual(self.manifest.read_bytes(), expected[1]); self.clean()

    @unittest.skipUnless(os.name == 'nt', 'Windows UTF-16 native path semantics')
    def test_real_mapped_non_ascii_path_publishes_exact_bytes(self):
        path = self.root/'\u6a21\u578b-\u03bc-\U0001f6e9.glb'; path.write_bytes(self.old)
        try:
            with mapped_reader(path, True) as view:
                with files.atomic_write_stream(path, 'wb') as stream: stream.write(b'complete Unicode path')
                self.assertEqual(path.read_bytes(), b'complete Unicode path')
                self.assertEqual(ctypes.string_at(view, len(self.old)), self.old)
        finally: path.unlink(missing_ok=True)
        self.clean()

    @unittest.skipUnless(os.name == 'nt', 'Windows sharing refusal semantics')
    def test_real_nondeleting_reader_refuses_bounded_replace_and_preserves_old_bytes(self):
        with mapped_reader(self.path, False):
            with mock.patch.object(files.time, 'monotonic', side_effect=[0., 0., files.PATIENCE_S+1.]), mock.patch.object(files.time, 'sleep') as sleep:
                with self.assertRaises(OSError):
                    model3d.finish(self.builder(), [0], 'fixture', str(self.path))
            self.assertEqual(sleep.call_count, 1)
            self.assertEqual(self.path.read_bytes(), self.old)
            self.assertEqual(self.manifest.read_bytes(), b'old manifest\n'); self.clean()


if __name__ == '__main__': unittest.main()
